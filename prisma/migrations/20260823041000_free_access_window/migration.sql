-- NULLABLE, NO DEFAULT, NO BACKFILL. That is deliberate and it is what makes this
-- safe to apply BEFORE the code deploys:
--   * every existing row becomes NULL = "never started", which is the state a user
--     is allowed to start FROM, not a state they are refused in;
--   * the running (pre-deploy) code never reads the column, so applying it early
--     changes nothing for anyone;
--   * a DEFAULT now() would have silently started the clock for all existing users
--     and expired them three days later without one of them practising.
--
-- Generated by `prisma migrate diff --from-schema-datasource --to-schema-datamodel`
-- against the live database on 2026-08-23, which reported this column as the ONLY
-- difference — a hand-written ALTER is how AlmiPrep ended up wanting a second
-- migration while `migrate status` still said "up to date".
ALTER TABLE "User" ADD COLUMN     "freeAccessStartedAt" TIMESTAMP(3);
