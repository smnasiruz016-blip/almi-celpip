// RR-418 · writes scripts/seed/rr418-overrides.ts: for every seed item that RR-418 changes (Parts B, C, F), its new title, prompt,
// guidanceNote and payload, keyed by the item's ORIGINAL taskType + title; and the renamed titles. seed:prod applies it, so a re-seed
// gives the same bank as production after the owner's write — without the seed ever reading the inputs. It never adds an item.
// The test (rr418.test.ts) rebuilds it in memory and fails if the committed file differs.
//   npx tsx scripts/factory/rr418/build-seed-overrides.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { checkInputs } from "../../../src/lib/factory/rr418/inputs";
import { SOURCE, seedWithRr418, keyOf, RENAMES } from "./seed-plan";

export const OVERRIDES_FILE = join("scripts", "seed", "rr418-overrides.ts");

export function buildOverrides(): string {
  const { items } = seedWithRr418();
  const o: Record<string, { title: string; prompt: string; guidanceNote: string | null; payload: unknown }> = {};
  SOURCE.forEach((src, i) => {
    const out = items[i];
    if (JSON.stringify(out) === JSON.stringify(src)) return;
    o[keyOf(String(src.taskType), src.title)] = { title: out.title, prompt: out.prompt, guidanceNote: out.guidanceNote ?? null, payload: out.payload };
  });
  return [
    "// RR-418 · GENERATED by build-seed-overrides.ts (RR-418 folder of the scripts) — do not edit by hand. For each seed item that RR-418 changes",
    "// (keyed by its ORIGINAL taskType::title): the new title, prompt, guidanceNote and payload, exactly as the owner's write leaves the",
    "// live row. seed:prod (append.ts) applies it to the five seed files. It changes items already in the seed; it never adds one.",
    "",
    `export const RR418_RENAMES: { taskType: string; from: string; to: string }[] = ${JSON.stringify(RENAMES(), null, 1)};`,
    "",
    `export const RR418_OVERRIDES: Record<string, { title: string; prompt: string; guidanceNote: string | null; payload: unknown }> = ${JSON.stringify(o, null, 1)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && /build-seed-overrides\.ts$/.test(process.argv[1])) {
  checkInputs();
  writeFileSync(OVERRIDES_FILE, buildOverrides());
  console.log(`wrote ${OVERRIDES_FILE}`);
}
